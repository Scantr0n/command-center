// The dashboard's graph only ever calls d3.select/selectAll (d3-selection)
// and the force layout (d3-force, which itself needs d3-quadtree, d3-dispatch,
// and d3-timer), not the other ~30 modules in the full d3 bundle. Each of
// those five modules is a real npm dependency already pinned by d3 itself in
// package-lock.json, so this just concatenates their prebuilt UMD minified
// files in dependency order (each attaches to the shared global d3 object,
// and d3-force reads its deps back off that same object) into one small
// vendor file instead of shipping the full ~280KB bundle for ~5% of it.
//
// Run after `npm install` whenever the d3 dependency version changes:
//   node scripts/build-vendor-d3.js

const fs = require('fs');
const path = require('path');

const MODULES = ['d3-dispatch', 'd3-timer', 'd3-quadtree', 'd3-force', 'd3-selection'];
const OUT_FILE = path.join(__dirname, '..', 'public', 'vendor', 'd3-force-selection.min.js');

const banner = `// Minimal d3 build: ${MODULES.join(' + ')} only.\n` +
  `// Generated by scripts/build-vendor-d3.js, do not hand-edit.\n\n`;

const parts = MODULES.map(mod => {
  const file = path.join(__dirname, '..', 'node_modules', mod, 'dist', `${mod}.min.js`);
  return fs.readFileSync(file, 'utf8').trim();
});

fs.writeFileSync(OUT_FILE, banner + parts.join('\n'));
console.log(`Wrote ${OUT_FILE} (${fs.statSync(OUT_FILE).size} bytes) from: ${MODULES.join(', ')}`);
