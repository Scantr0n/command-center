// Self-hosts the exact Google Fonts weights the dashboard uses, instead of
// loading them from fonts.googleapis.com/fonts.gstatic.com at runtime. Two
// real reasons, not just performance: (1) sw.js's fetch handler explicitly
// skips every cross-origin request, so a fully offline reload previously
// fell back to system fonts even though every other asset the app needs
// was cached, undermining the "render fully offline" intent sw.js's own
// header comment describes; (2) one fewer third-party request on every
// load, same local-first spirit as vendoring d3 instead of a CDN copy.
//
// Pulls the real Latin WOFF2 files straight out of the @fontsource npm
// packages (already pinned in package-lock.json), picking only the weights
// tailwind.config.js's fontFamily block actually uses: Inter 400/500/600,
// Manrope 600/700/800, JetBrains Mono 400/500. No network fetch beyond
// `npm install`, same reproducible-from-node_modules convention as
// build-vendor-d3.js.
//
// Run after `npm install` whenever a font package version or weight changes:
//   node scripts/build-vendor-fonts.js

const fs = require('fs');
const path = require('path');

const FAMILIES = [
  { pkg: 'inter', family: 'Inter', weights: [400, 500, 600] },
  { pkg: 'manrope', family: 'Manrope', weights: [600, 700, 800] },
  { pkg: 'jetbrains-mono', family: 'JetBrains Mono', weights: [400, 500] }
];

const OUT_DIR = path.join(__dirname, '..', 'public', 'vendor', 'fonts');
fs.mkdirSync(OUT_DIR, { recursive: true });

let css = `/* Self-hosted subset of Inter/Manrope/JetBrains Mono (Latin, the only\n` +
  ` * weights tailwind.config.js's fontFamily block uses). Generated by\n` +
  ` * scripts/build-vendor-fonts.js, do not hand-edit. */\n\n`;

FAMILIES.forEach(({ pkg, family, weights }) => {
  weights.forEach(weight => {
    const slug = pkg === 'jetbrains-mono' ? 'jetbrains-mono' : pkg;
    const srcFile = path.join(__dirname, '..', 'node_modules', '@fontsource', pkg, 'files', `${slug}-latin-${weight}-normal.woff2`);
    const destName = `${slug}-${weight}.woff2`;
    fs.copyFileSync(srcFile, path.join(OUT_DIR, destName));
    css += `@font-face {\n` +
      `  font-family: '${family}';\n` +
      `  font-style: normal;\n` +
      `  font-display: swap;\n` +
      `  font-weight: ${weight};\n` +
      `  src: url('./${destName}') format('woff2');\n` +
      `}\n\n`;
  });
});

fs.writeFileSync(path.join(OUT_DIR, 'fonts.css'), css);
const fileCount = FAMILIES.reduce((n, f) => n + f.weights.length, 0);
console.log(`Wrote ${fileCount} WOFF2 files + fonts.css to ${path.relative(path.join(__dirname, '..'), OUT_DIR)}`);
